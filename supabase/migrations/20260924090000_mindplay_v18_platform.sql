create or replace function public.get_mindplay_stats(p_days integer default 30)
returns jsonb language sql stable security invoker set search_path=public as $$
with scoped as (
 select * from public.analytics_events
 where p_days=0 or created_at>=now()-make_interval(days=>greatest(1,least(p_days,3650)))
), summary as (
 select
  count(*) filter(where event_type='page_view') page_views,
  count(distinct visitor_id) filter(where event_type='page_view') visitors,
  count(*) filter(where event_type='game_start') game_starts,
  count(*) filter(where event_type='game_complete') game_completions,
  count(*) filter(where event_type='guess_correct') correct_guesses,
  count(*) filter(where event_type='guess_wrong') wrong_guesses,
  count(*) filter(where event_type='game_replay') replays,
  count(*) filter(where event_type='share') shares
 from scoped
), game_stats as (
 select c.game_id,c.title,c.sort_order,
  count(*) filter(where e.event_type='game_start') starts,
  count(*) filter(where e.event_type='game_complete') completions,
  count(*) filter(where e.event_type='guess_correct') correct,
  count(*) filter(where e.event_type='guess_wrong') wrong,
  count(*) filter(where e.event_type='game_replay') replays,
  count(*) filter(where e.event_type='share') shares
 from public.game_configs c left join scoped e on e.game_id=c.game_id
 where c.enabled=true group by c.game_id,c.title,c.sort_order
), daily as (
 select (created_at at time zone 'Asia/Bangkok')::date day,
  count(*) filter(where event_type='page_view') page_views,
  count(distinct visitor_id) filter(where event_type='page_view') visitors,
  count(*) filter(where event_type='game_start') game_starts,
  count(*) filter(where event_type='game_complete') completions
 from scoped group by 1
)
select jsonb_build_object(
 'period_days',p_days,
 'summary',(select jsonb_build_object(
  'page_views',page_views,'visitors',visitors,'game_starts',game_starts,'game_completions',game_completions,
  'correct_guesses',correct_guesses,'wrong_guesses',wrong_guesses,'replays',replays,'shares',shares,
  'completion_rate',case when game_starts=0 then 0 else round((game_completions::numeric/game_starts)*100,1) end,
  'correct_rate',case when(correct_guesses+wrong_guesses)=0 then 0 else round((correct_guesses::numeric/(correct_guesses+wrong_guesses))*100,1) end
 ) from summary),
 'games',coalesce((select jsonb_agg(jsonb_build_object(
  'game_id',game_id,'title',title,'starts',starts,'completions',completions,'correct',correct,'wrong',wrong,'replays',replays,'shares',shares,
  'completion_rate',case when starts=0 then 0 else round((completions::numeric/starts)*100,1) end,
  'correct_rate',case when(correct+wrong)=0 then 0 else round((correct::numeric/(correct+wrong))*100,1) end
 ) order by starts desc,sort_order) from game_stats),'[]'::jsonb),
 'daily',coalesce((select jsonb_agg(jsonb_build_object(
  'day',day,'page_views',page_views,'visitors',visitors,'game_starts',game_starts,'completions',completions
 ) order by day) from daily),'[]'::jsonb),
 'active_now',(select count(*) from public.game_sessions where status='active' and updated_at>=now()-interval '15 minutes')
);
$$;

revoke all on function public.get_mindplay_stats(integer) from public,anon,authenticated;
grant execute on function public.get_mindplay_stats(integer) to service_role;
