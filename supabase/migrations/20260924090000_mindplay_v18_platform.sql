create table if not exists public.visitor_sessions (
  id uuid primary key,
  first_path text not null default '/',
  started_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create table if not exists public.game_sessions (
  id uuid primary key default gen_random_uuid(),
  visitor_id uuid not null references public.visitor_sessions(id) on delete cascade,
  game_id text not null check (game_id in ('card-mind','number-mind','symbol-mind','word-mind','sealed-prediction')),
  status text not null default 'active' check (status in ('active','completed','abandoned')),
  token_hash text not null,
  state jsonb not null default '{}'::jsonb,
  result_correct boolean,
  replay_count integer not null default 0 check (replay_count >= 0),
  started_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null references public.visitor_sessions(id) on delete cascade,
  game_session_id uuid references public.game_sessions(id) on delete set null,
  event_type text not null check (event_type in ('page_view','game_view','game_start','game_complete','guess_correct','guess_wrong','game_replay','share')),
  game_id text check (game_id is null or game_id in ('card-mind','number-mind','symbol-mind','word-mind','sealed-prediction')),
  path text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.game_configs (
  game_id text primary key check (game_id in ('card-mind','number-mind','symbol-mind','word-mind','sealed-prediction')),
  title text not null,
  enabled boolean not null default true,
  sort_order smallint not null,
  updated_at timestamptz not null default now()
);

